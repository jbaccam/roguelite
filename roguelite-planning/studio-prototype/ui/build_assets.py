"""Original vector UI art; supplied mockups are inspiration, never edited.
Writes editable SVG sources and supersampled PNG derivatives for Roblox.
"""
from pathlib import Path
from PIL import Image, ImageDraw

OUT = Path(__file__).parent / 'assets'
OUT.mkdir(exist_ok=True)
S = 3
class Art:
    def __init__(self, name):
        self.name = name
        self.im = Image.new('RGBA', (256*S, 256*S))
        self.d = ImageDraw.Draw(self.im)
        self.svg = []
    def poly(self, pts, color):
        self.d.polygon([(round(x*S), round(y*S)) for x,y in pts], fill=color)
        self.svg.append(f'<polygon points="{" ".join(f"{x},{y}" for x,y in pts)}" fill="{color}"/>')
    def ellipse(self, box, color):
        self.d.ellipse(tuple(int(x*S) for x in box), fill=color)
        x,y,r,b=box
        self.svg.append(f'<ellipse cx="{(x+r)/2}" cy="{(y+b)/2}" rx="{(r-x)/2}" ry="{(b-y)/2}" fill="{color}"/>')
    def rect(self, x,y,w,h,c): self.poly([(x,y),(x+w,y),(x+w,y+h),(x,y+h)],c)
    def oct(self, inset, cut, color):
        a,b=inset,256-inset
        self.poly([(a+cut,a),(b-cut,a),(b,a+cut),(b,b-cut),(b-cut,b),(a+cut,b),(a,b-cut),(a,a+cut)],color)
    def save(self):
        self.im.resize((256,256),Image.Resampling.LANCZOS).save(OUT/(self.name+'.png'))
        (OUT/(self.name+'.svg')).write_text('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">'+''.join(self.svg)+'</svg>')

